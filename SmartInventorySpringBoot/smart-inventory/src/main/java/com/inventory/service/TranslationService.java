    /** Adds key/value pairs in alternating order. */
    private void put(Map<String, String> map, String... pairs) {
        if (pairs.length % 2 != 0) {
            throw new IllegalArgumentException("Translation entries must be key/value pairs.");
        }
        for (int i = 0; i < pairs.length; i += 2) {
            map.put(pairs[i], pairs[i + 1]);
        }
    }

    /** Returns translations for the requested language; English is the fallback. */
    public Map<String, String> getTranslations(String language) {
        String code = language == null ? "en" : language.trim().toLowerCase(Locale.ROOT);
        return translations.getOrDefault(code, translations.get("en"));
    }
